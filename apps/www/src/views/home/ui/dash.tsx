/**
 * 재료를 못 받은 블록의 자리 — «—» (#524 · ssccops#385 수용 기준 «재료 하나가 실패해도 그 블록만»).
 *
 * 오류 문장을 쓰지 않는 것은 홈이 첫 화면이라서다 — 서버가 잠깐 닿지 않을 때 «불러오지
 * 못했습니다»가 세 블록에 나란히 서면 화면이 고장 난 것처럼 보이는데, 사람이 할 수 있는 일은
 * 새로고침 하나다. 보조기기에는 그 뜻을 `aria-label`로 준다.
 */
export function Dash() {
  return (
    <p className="text-[15px] text-n500" aria-label="불러오지 못했습니다">
      —
    </p>
  );
}
