import { CAPABILITY, type Capability } from "@/entities/session";

/*
 * 행사 삭제·복구의 **요구 권한과 문구** (ssccops-web#391 · ADR-0020 · 서버 ssccops-server#347).
 *
 * 폼의 form-delete-copy.ts와 같은 자리다 — 잠긴 버튼의 `title`, 확인 시트의 제목·부제·경고,
 * 서버가 거절했을 때의 문장이 한 판단의 앞뒷면이라 한 파일에 둔다. 흩어 놓으면 같은 상황이
 * 화면마다 다른 문장으로 갈린다.
 *
 * ── 보관과 삭제는 다른 뜻이다 ──────────────────────────────────
 * ADR-0014는 삭제를 걷어내고 보관 하나로 일원화했고, ADR-0020이 그 결정을 뒤집었다. 두 장치를
 * 함께 두는 근거는 뜻이 갈린다는 것이다 — **보관은 끝난 행사를 공개에서 내리되 운영 기록으로
 * 남기는 것, 삭제는 잘못 만든 것을 목록에서 치우되 되돌릴 수 있게 두는 것.** 아래 문구는 그
 * 구분을 흐리지 않게 «보관»이라는 말을 쓰지 않는다.
 */

/**
 * 삭제·복구·휴지통 조회에 요구하는 권한.
 *
 * 관리 API 전체가 `EVENT_MANAGE` 한 가지다(서버 판정 — 목록 조회까지 같은 권한이라 메뉴 자체를
 * 그것으로 게이트한다). 전용 `EVENT_DELETE`를 두지 않은 것은 폼이 `FORM_DELETE`를 두지 않은
 * 판단과 같다 — 이 권한 보유자는 이미 PUT 하나로 행사를 통째로 갈아엎을 수 있고, 소프트 삭제는
 * 그중 유일하게 되돌릴 수 있는 조작이다. **되살리기가 같은 권한인 것이 요점이다** — 지울 수
 * 있는 사람이 되돌릴 수 없으면 자기가 저지른 것을 스스로 수습하지 못한다(ADR-0020 규칙표).
 */
export const EVENT_DELETE_CAPABILITY: Capability = CAPABILITY.EVENT_MANAGE;

/**
 * 잠긴 삭제·복구 버튼에 붙는 사유이자 403의 문장.
 *
 * 요구 권한을 이름으로 밝히는 것은 AGENTS.md §화면 문구의 규칙이다. 표기는 행사 목록의 다른
 * 잠금(`NO_MANAGE`)과 같은 `행사 관리(EVENT_MANAGE)`다.
 */
export const NO_EVENT_DELETE =
  "행사를 지우거나 되살릴 권한이 없습니다 — 행사 관리(EVENT_MANAGE) 권한이 필요합니다";

/** 삭제 확인 시트의 제목 — 지운 뒤 어떻게 되는지는 `EVENT_DELETE_HINT`가 말한다 */
export const EVENT_DELETE_CONFIRM_TITLE = "행사를 지울까요?";

/** 삭제 확인 시트의 부제 — 되살릴 자리를 이름으로 짚는다(그 화면이 이 결정의 전제다) */
export const EVENT_DELETE_HINT =
  "지운 행사는 목록과 공개 화면에서 빠지고 '지운 행사'에서 되살릴 수 있습니다";

/**
 * **이 결정에서 가장 놓치기 쉬운 결과.**
 *
 * 참가자가 있는 행사를 지우면 운영진의 목록에서만 빠지는 것이 아니라 **참가자의 '내 신청'에서도
 * 그 행사가 사라진다**(ADR-0020 규칙표 — 데이터는 남고 화면에서만 빠진다). 운영진에게는 이것이
 * 화면에 전혀 드러나지 않는다 — 자기 목록에서 한 줄이 사라지는 것만 보고 남의 화면에서 무슨
 * 일이 났는지는 알 방법이 없다. **그래서 확인 문구가 말해야 한다.** 폼이 응답 수를 두고 하는
 * 판단(formDeleteResponseWarning)과 같다.
 *
 * 숫자를 말할 수 있는 것은 **확정 참가자뿐이다** — 목록 응답에 오는 집계가 `confirmedCount`
 * 하나라서다(심사 중 응답 수는 오지 않는다 · 폼 연결 변경 시트가 같은 이유로 확정만 센다).
 * 0명이면 이 문장 자체를 띄우지 않는다 — 없는 위험을 경고하면 다음번 진짜 경고도 넘겨진다.
 */
export function eventDeleteParticipantWarning(confirmedCount: number): string {
  return `확정 참가자 ${confirmedCount}명의 '내 신청'에서 이 행사가 사라집니다 — 되살리면 함께 돌아옵니다`;
}

/** 확정 참가자가 0명일 때의 확인 문구 — 지금 사라지는 것이 목록의 한 줄뿐이라는 사실만 말한다 */
export const EVENT_DELETE_NO_PARTICIPANT_NOTE =
  "아직 확정된 참가자가 없습니다. 지워도 사라지는 것은 목록의 이 행사뿐입니다.";

/**
 * 복구가 무엇을 되돌리는지 — '지운 행사' 화면이 한 번, 되살리기 버튼의 `title`이 한 번 말한다.
 *
 * 복제(사본은 DRAFT이고 기간·참가자를 승계하지 않는다)와 헷갈리기 가장 쉬운 자리다. 복구는
 * 사본을 만드는 것이 아니라 **지우기 전 그 행사 그대로**를 되돌린다 — 게시 중이었으면 다시
 * 게시 중이고, 공개 화면에도 다시 뜬다.
 */
export const EVENT_RESTORE_NOTE =
  "되살리면 게시 상태·참가자·연결 폼이 지우기 전 그대로 돌아옵니다";
