"use client";

import { hasCapability, useSessionStore, type Capability } from "@/entities/session";

/*
 * 화면이 권한을 묻는 **유일한 통로** (#29).
 *
 * ── 왜 훅 하나뿐인가 ───────────────────────────────────────────
 * 화면마다 `member.capabilities.includes("FORM_WRITE")`를 쓰기 시작하면 세 가지가 곧바로
 * 갈린다 — 미가입·미로그인(member === null)을 허용으로 볼지, 배열이 비었을 때의 기본값,
 * 그리고 코드 문자열의 오타. 판정을 한 줄로 모아 두면 그 셋이 한 번만 정해진다. 서버도 같은
 * 이유로 AuthorityPolicy 하나에 판정을 몰아 두었다.
 *
 * 훅은 **배열에 코드가 있는지만** 본다. 역할 이름·서열이나 권한 트리 펼침을 웹에서 다시
 * 계산하지 않는다(entities/session/model/types.ts의 CAPABILITY 주석 참고).
 *
 * ── 감출 것인가 잠글 것인가: 자리에 따라 다르게 정했다 ─────────────
 * 한쪽으로 통일하지 않았다. 같은 "권한 없음"이라도 사용자가 그 자리에서 알아야 할 것이 다르다.
 *
 * **사이드바 메뉴는 감춘다.** 사이드바는 "여기서 무엇을 할 수 있는가"의 목차다. 잠긴 항목을
 * 남겨 두면 눌러도 아무 일이 없어 이유를 물어볼 곳조차 없고(툴팁은 마우스를 올려야 보이며
 * 터치에서는 아예 안 보인다), 무엇보다 **그 뒤의 화면이 실제로 쓸 수 없다** — 업무 목록은
 * 조회부터 WORK_MANAGE로 막혀 있어 들어가 봐야 오류 화면뿐이다. 갈 수 없는 곳을 목차에
 * 남기면 목차 전체를 믿을 수 없게 된다.
 *
 * **화면 안의 동작 버튼은 잠근다(사유를 title로 붙인다).** 여기서는 사용자가 이미 그 화면을
 * 보고 있다. 폼 목록을 멀쩡히 보는 사람에게서 '수정'만 소리 없이 사라지면 기능이 없어진
 * 것인지 고장인지 알 수 없고, 어제까지 쓰던 사람은 자기 계정 문제라는 것을 짐작조차 못 한다.
 * 잠긴 버튼은 "이 기능은 있고, 지금 당신에게 권한이 없다"까지 말해 준다 — 그래야 운영진에게
 * 역할을 요청하러 갈 수 있다. 어수선해지는 대가는 치를 만하다.
 *
 * 요약하면 **이동은 감추고, 동작은 잠근다.**
 */
export function useCan(capability: Capability): boolean {
  return useSessionStore((s) => hasCapability(s.member, capability));
}
